// Generates the Zetaris Lightning SQL that registers every Trust Desk source
// on a real Zetaris instance. Output: sql/zetaris/01_trustdesk_create.sql
import fs from "node:fs";
import { SOURCES, AGENT_CARD_SOURCES, AGENT_CARD_COLUMNS, LIGHTNING_DB, CONTAINER } from "../src/zetaris/sources.ts";

const rest = (table: string, endpoint: string) => `CREATE LIGHTNING REST TABLE ${table} FROM ${LIGHTNING_DB} REQUEST(
    endpoint "${endpoint}",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
) BODY ();
CACHE TABLE ${LIGHTNING_DB}.${table};`;

const out: string[] = [
  "-- AgentID Trust Desk: Zetaris federation layer (generated by scripts/gen-lightning-sql.ts).",
  "-- Pattern follows zetaris/getting-started open_data/rest_apis (REST table -> CACHE -> SCHEMASTORE VIEW).",
  "-- Run once in the Zetaris SQL Editor (or `npm run zetaris:check -- --apply`).",
  "-- The four internal datasets are SYNTHETIC demo data served from GitHub Pages; in production you would point",
  "-- the same views at the real systems (Postgres CRM, Jira, API-gateway warehouse) with CREATE LIGHTNING DATABASE ... JDBC.",
  "",
  `CREATE LIGHTNING DATABASE ${LIGHTNING_DB} DESCRIBE BY "AgentID Trust Desk sources (REST/JSON)";`,
  `CREATE SCHEMASTORE CONTAINER ${CONTAINER};`,
  "",
];
for (const s of SOURCES) {
  out.push(`-- ${s.system}`, rest(s.restTable, s.endpoint), "");
  out.push(`CREATE SCHEMASTORE VIEW ${s.view} WITH CONTAINER ${CONTAINER} AS
SELECT
${s.columns.map((c) => `    r.${c.expr ?? c.name} AS ${c.name}`).join(",\n")}
FROM ${LIGHTNING_DB.toLowerCase()}.${s.restTable}
LATERAL VIEW explode(records) AS r;`, "");
}
out.push("-- Public ERC-8004 registration files (agentURI) for each agent");
for (const c of AGENT_CARD_SOURCES) out.push(rest(c.restTable, c.endpoint), "");
out.push(`CREATE SCHEMASTORE VIEW agent_cards WITH CONTAINER ${CONTAINER} AS
${AGENT_CARD_SOURCES.map((c) => `SELECT ${AGENT_CARD_COLUMNS.map((k) => k.name === "agent_uri" ? `'${c.endpoint}' AS agent_uri` : `${k.expr ?? k.name} AS ${k.name}`).join(", ")} FROM ${LIGHTNING_DB.toLowerCase()}.${c.restTable}`).join("\nUNION ALL\n")};`, "");
out.push("-- Verify:", ...[...SOURCES.map((s) => s.view), "agent_cards"].map((v) => `-- SELECT COUNT(*) FROM ${CONTAINER}.${v};`), "");
fs.writeFileSync("sql/zetaris/01_trustdesk_create.sql", out.join("\n"));
console.log("wrote sql/zetaris/01_trustdesk_create.sql");
